(* The window system's cursors: rio's own (principia's
 * windows/rio/data.c: crosscursor, sightcursor; xix's Cursors), their
 * bits as they are there. No Cursors.mli: data. *)

let bytes l = String.init (List.length l) (fun k -> Char.chr (List.nth l k))

(* a cross: a rectangle is to be swept out (New) *)
let cross : Cursor.t = { offset = Point.v (-7) (-7);
  clr = bytes [ 0x03; 0xC0; 0x03; 0xC0; 0x03; 0xC0; 0x03; 0xC0; 0x03; 0xC0; 0x03; 0xC0; 0xFF; 0xFF; 0xFF; 0xFF;
                0xFF; 0xFF; 0xFF; 0xFF; 0x03; 0xC0; 0x03; 0xC0; 0x03; 0xC0; 0x03; 0xC0; 0x03; 0xC0; 0x03; 0xC0 ];
  set = bytes [ 0x00; 0x00; 0x01; 0x80; 0x01; 0x80; 0x01; 0x80; 0x01; 0x80; 0x01; 0x80; 0x01; 0x80; 0x7F; 0xFE;
                0x7F; 0xFE; 0x01; 0x80; 0x01; 0x80; 0x01; 0x80; 0x01; 0x80; 0x01; 0x80; 0x01; 0x80; 0x00; 0x00 ] }

(* a sight: a window is to be pointed at (Delete) *)
let sight : Cursor.t = { offset = Point.v (-7) (-7);
  clr = bytes [ 0x1F; 0xF8; 0x3F; 0xFC; 0x7F; 0xFE; 0xFB; 0xDF; 0xF3; 0xCF; 0xE3; 0xC7; 0xFF; 0xFF; 0xFF; 0xFF;
                0xFF; 0xFF; 0xFF; 0xFF; 0xE3; 0xC7; 0xF3; 0xCF; 0x7B; 0xDF; 0x7F; 0xFE; 0x3F; 0xFC; 0x1F; 0xF8 ];
  set = bytes [ 0x00; 0x00; 0x0F; 0xF0; 0x31; 0x8C; 0x21; 0x84; 0x41; 0x82; 0x41; 0x82; 0x41; 0x82; 0x7F; 0xFE;
                0x7F; 0xFE; 0x41; 0x82; 0x41; 0x82; 0x41; 0x82; 0x21; 0x84; 0x31; 0x8C; 0x0F; 0xF0; 0x00; 0x00 ] }

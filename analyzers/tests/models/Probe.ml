let hashtbl_remove () = Hashtbl.remove h "a"
let hashtbl_mem () = Hashtbl.mem h "a"
let hashtbl_find () = Hashtbl.find h "a"
let hashtbl_find_all () = Hashtbl.find_all h "a"
let hashtbl_find_opt () = Hashtbl.find_opt h "a"
let hashtbl_iter () = Hashtbl.iter (fun _ v -> ignore (f v)) h
let hashtbl_fold () = Hashtbl.fold (fun _ v a -> f v + a) h 0
let hashtbl_filter_map_inplace () = Hashtbl.filter_map_inplace (fun _ v -> fo v) h


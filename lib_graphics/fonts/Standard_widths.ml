let index : (string, int) Hashtbl.t = Hashtbl.create 256
let () = Array.iteri (fun i n -> Hashtbl.replace index n i) names

let has (s : string) (part : string) : bool =
  let n = String.length part in
  let rec go i = i + n <= String.length s && (String.sub s i n = part || go (i + 1)) in
  go 0

(* [width font glyph]: a glyph's advance in thousandths of an em, for
 * a font known by its name alone: Courier's, Helvetica's (and Arial's,
 * made to its measures), else Times's; in its weight and slant *)
let width (font : string) (glyph : string) : int option =
  let f = String.lowercase_ascii font in
  if has f "courier" then Some 600
  else
    let bold = has f "bold" and italic = has f "italic" || has f "oblique" in
    let table =
      if has f "helvetica" || has f "arial" then if bold then helvetica_bold else helvetica
      else if bold && italic then times_bold_italic
      else if bold then times_bold
      else if italic then times_italic
      else times_roman
    in
    Option.map (fun i -> table.(i)) (Hashtbl.find_opt index glyph)

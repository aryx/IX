 * own: what may escape it, and the functions given it called, the same
 * with the models and without (-no-models, the library as written) *)
let h : (string, int) Hashtbl.t = Hashtbl.create 8
let l : int list = [ 1; 2 ]
let al : (string * int) list = [ ("a", 1) ]
let ll : int list list = [ l ]
let f (x : int) : int = x
let p (x : int) : bool = x > 0
let fo (x : int) : int option = Some x
let fl (x : int) : int list = [ x ]
let cmp (a : int) (b : int) : int = a - b

let hashtbl_create () = Hashtbl.create 8
let hashtbl_clear () = Hashtbl.clear h

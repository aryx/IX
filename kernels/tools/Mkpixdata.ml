(* mini-mkpixdata: the OCaml pixels' data, from principia's C where it is
 * data, not code: libmemdraw/cmap.c's default colour map (mkcmap.c's
 * output: cmap2rgb, 256 colours; rgb2cmap, 4096 entries by 4-bit red,
 * green, blue) and libdraw/defont.c's defontdata (lucm/latin1.9, the
 * default font, uncompressed), written as OCaml strings: the kernel's
 * Memdata.ml and its interface (lib_graphics/ocaml, PIXEL=ocaml), or,
 * with -font, the client's lib_graphics/Font_default.ml.
 *
 * Run once: its output is in the repository, the build does not run
 * it, nor need principia; again only if principia's C changes.
 * (old: kernels/9pi/conf/mkpixdata.py and lib_graphics/tools/defont.py) *)

type caps = < Cap.open_in; Cap.open_out; Cap.stdout; Cap.stderr >

let help = {|usage: mini-mkpixdata principia dir | -font principia
The pixels' data, from principia's lib_graphics C, as OCaml strings.
  mini-mkpixdata ~/principia kernels/9pi/lib_graphics
                                      its Memdata.ml and Memdata.mli: the
                                      colour map and the default font
  mini-mkpixdata -font ~/principia > lib_graphics/Font_default.ml
                                      the default font alone
|}

let header = "(* Claude Code\n * Copyright (C) 2026 Yoann Padioleau. LGPL 2.1: see license.txt. *)\n\n"

(* where sub is in s, from i on *)
let rec find (s : string) (sub : string) (i : int) : int =
  if i + String.length sub > String.length s then failwith ("no " ^ sub)
  else if String.sub s i (String.length sub) = sub then i
  else find s sub (i + 1)

let is_hex c = (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F')

(* the 0x numbers of s, in order *)
let numbers (s : string) : int list =
  let n = String.length s in
  let rec go i acc =
    if i + 2 >= n then List.rev acc
    else if s.[i] = '0' && s.[i + 1] = 'x' && is_hex s.[i + 2] then begin
      let j = ref (i + 2) in
      while !j < n && is_hex s.[!j] do incr j done;
      go !j (int_of_string ("0x" ^ String.sub s (i + 2) (!j - i - 2)) :: acc)
    end
    else go (i + 1) acc
  in
  go 0 []

(* the lines of an OCaml string: 32 bytes each, \ddd *)
let lines (bs : int list) : string list =
  let rec go bs acc cur k =
    match bs with
    | [] -> List.rev (if cur = [] then acc else String.concat "" (List.rev cur) :: acc)
    | b :: rest ->
        let cur = Printf.sprintf "\\%03d" b :: cur in
        if k = 31 then go rest (String.concat "" (List.rev cur) :: acc) [] 0
        else go rest acc cur (k + 1)
  in
  List.map (fun l -> "\"" ^ l ^ "\"") (go bs [] [] 0)

let literal (name : string) (bs : int list) : string =
  Printf.sprintf "let %s = String.concat \"\" [\n  %s ]\n" name (String.concat ";\n  " (lines bs))

let rec take n l = if n = 0 then [] else match l with [] -> [] | x :: r -> x :: take (n - 1) r
let rec drop n l = if n = 0 then l else match l with [] -> [] | _ :: r -> drop (n - 1) r

let gfx caps principia file = FS.read caps (Fpath.v (Filename.concat principia ("lib_graphics/" ^ file)))

let defont caps principia : int list =
  let text = gfx caps principia "libdraw/defont.c" in
  let i = find text "defontdata[]" 0 in
  numbers (String.sub text i (find text "};" i - i))

let memdata (caps : < caps; .. >) (principia : string) (dir : string) : unit =
  let text = gfx caps principia "libmemdraw/cmap.c" in
  let i = find text "cmap2rgb" 0 in
  let cmap = numbers (String.sub text i (String.length text - i)) in
  if List.length cmap < 768 + 4096 then failwith "cmap.c: too few numbers";
  let file name = Fpath.v (Filename.concat dir name) in
  FS.write caps (file "Memdata.ml") (String.concat "" [
    header;
    "(* Generated by mini-mkpixdata from principia's cmap.c and defont.c\n";
    " * (Plan 9's default colour map and default font): see Memdata.mli. *)\n";
    literal "cmap2rgb" (take 768 cmap);
    literal "rgb2cmap" (take 4096 (drop 768 cmap));
    literal "defont" (defont caps principia) ]);
  FS.write caps (file "Memdata.mli") (String.concat "" [
    header;
    "(* Generated by mini-mkpixdata: the default colour map (cmap2rgb: 256\n";
    " * colours' r, g, b; rgb2cmap: by 4-bit r, g, b), the default font *)\n";
    "val cmap2rgb : string\nval rgb2cmap : string\nval defont : string\n" ])

let font_default (caps : < caps; .. >) (principia : string) : unit =
  let data = defont caps principia in
  Console.print caps (String.concat "" [
    "(* Generated by mini-mkpixdata -font from principia's lib_graphics/libdraw/defont.c:\n";
    " * Plan 9's default font (lucm/latin1.9; Lucida Sans Typewriter, Bigelow &\n";
    Printf.sprintf " * Holmes's, as Plan 9 gives it), %d bytes. Font\n" (List.length data);
    " * reads it: an image's header and pixels, then a subfont's header and its\n";
    " * characters. *)\n";
    "let data = String.concat \"\" [\n";
    String.concat "" (List.map (fun l -> "  " ^ l ^ ";\n") (lines data));
    "]\n" ])

let main (caps : < caps; .. >) (argv : string array) : int =
  try
    match List.tl (Array.to_list argv) with
    | args when List.mem "-h" args || List.mem "--help" args -> Console.print caps help; 0
    | [ "-font"; principia ] -> font_default caps principia; 0
    | [ principia; dir ] -> memdata caps principia dir; 0
    | _ -> Console.eprint caps "usage: mini-mkpixdata principia dir | -font principia   (-h: how)\n"; 1
  with Sys_error m | Failure m -> Console.eprint caps ("mini-mkpixdata: " ^ m ^ "\n"); 1

let () = Cap.main (fun caps -> Logging.setup caps ~name:"mini-mkpixdata"; CapStdlib.exit caps (main caps (CapSys.argv caps)))
